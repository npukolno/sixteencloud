const dictionaries: Record<Language, Record<string, string>> = { en, ru };

export function setLanguage(lang: Language): void {
  currentLanguage = lang;
}


export function t(key: string, params?: Record<string, string>): string {
  let text = dictionaries[currentLanguage][key] || dictionaries['en'][key] || key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      text = text.replace(`{${k}}`, v);
    }
  }
  return text;
}

export function getScriptTranslations(keys: string[]): Record<string, string> {
  const result: Record<string, string> = {};
  for (const key of keys) {
    result[key] = dictionaries[currentLanguage][key] || dictionaries['en'][key] || key;
  }
  return result;
}
